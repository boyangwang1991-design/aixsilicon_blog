const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'generated');
mkdirSync(out, { recursive: true });
const generated = [];
const palette = {
  navy: ['#17375e', '#edf4f9'], teal: ['#087f83', '#e5f7f4'],
  amber: ['#bd7510', '#fff3dd'], red: ['#c73535', '#fff0ef'],
  gray: ['#667a8b', '#f2f5f7'],
};
const e = s => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const t = (x, y, value, size=24, tone='navy', weight=400, anchor='start') => {
  const lines = Array.isArray(value) ? value : [value];
  return `<text x="${x}" y="${y}" fill="${palette[tone][0]}" font-size="${size}" font-weight="${weight}" text-anchor="${anchor}">${lines.map((v,i) => `<tspan x="${x}" dy="${i ? size*1.5 : 0}">${e(v)}</tspan>`).join('')}</text>`;
};
const box = (x,y,w,h,tone='navy',dash=false) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="17" fill="${palette[tone][1]}" stroke="${palette[tone][0]}" stroke-width="3"${dash?' stroke-dasharray="10 7"':''}/>`;
const card = (x,y,w,h,title,body=[],tone='navy',opts={}) => box(x,y,w,h,tone,!!opts.dash)+t(x+21,y+45,title,opts.titleSize||29,tone,700)+t(x+21,y+85,body,opts.bodySize||22,'navy');
const path = (points,tone='navy',dash=false,width=5) => `<polyline points="${points.map(p=>p.join(',')).join(' ')}" fill="none" stroke="${palette[tone][0]}" stroke-width="${width}" stroke-linejoin="round"${dash?' stroke-dasharray="10 8"':''} marker-end="url(#a-${tone})"/>`;
const line = (x1,y1,x2,y2,tone='gray',dash=false) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${palette[tone][0]}" stroke-width="3"${dash?' stroke-dasharray="10 8"':''}/>`;
const note = (x,y,w,label,tone='gray') => box(x,y,w,58,tone)+t(x+w/2,y+38,label,23,tone,700,'middle');
function save(name, body, desc) {
  const defs = Object.keys(palette).map(k=>`<marker id="a-${k}" markerWidth="12" markerHeight="12" refX="10" refY="6" orient="auto"><path d="M1 1 L11 6 L1 11 Z" fill="${palette[k][0]}"/></marker>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900" viewBox="0 0 1600 900" role="img" aria-label="${e(desc)}"><defs>${defs}</defs><rect width="1600" height="900" fill="#fcfdfd"/><g font-family="Microsoft YaHei, Noto Sans CJK SC, Arial, sans-serif">${body}</g></svg>`;
  writeFileSync(join(out,name),svg,'utf8');
  generated.push({ path: `assets/generated/${name}`, language: 'zh-CN', kind: '教学概念图', purpose: desc, sha256: createHash('sha256').update(svg,'utf8').digest('hex') });
}
function flow(name, desc, heading, stages, bottomHeading, bottomCards) {
  let s=t(65,68,heading,30,'navy',700);
  const gap=27, width=(1490-(stages.length-1)*gap)/stages.length;
  stages.forEach((v,i)=>{const x=55+i*(width+gap);s+=card(x,130,width,220,v[0],v.slice(1),i===stages.length-1?'teal':'navy',{titleSize:27,bodySize:21});if(i<stages.length-1)s+=path([[x+width,240],[x+width+gap-7,240]],'navy',false,4)});
  s+=line(55,405,1545,405)+t(65,460,bottomHeading,30,'amber',700);
  const bw=(1480-35*(bottomCards.length-1))/bottomCards.length;
  bottomCards.forEach((v,i)=>{s+=card(65+i*(bw+35),505,bw,220,v[0],v.slice(1),i===bottomCards.length-1?'teal':'amber',{titleSize:27,bodySize:22})});
  save(name,s,desc);
}
function matrix(name,desc,heading,headers,rows,footer){
  let s=t(65,65,heading,30,'navy',700);
  const xs=[60,390,770,1150], ws=[320,370,370,390];
  headers.forEach((h,i)=>{s+=box(xs[i],110,ws[i],70,'navy')+t(xs[i]+18,154,h,24,'navy',700)});
  rows.forEach((r,j)=>{const y=194+j*119; r.forEach((cell,i)=>{const tone=(i===0?'navy':(i===3?'teal':'gray'));s+=box(xs[i],y,ws[i],108,tone)+t(xs[i]+15,y+40,cell,20,'navy',i===0?700:400)})});
  s+=note(80,800,1440,footer,'amber'); save(name,s,desc);
}

